"""
instance.py
===========
Creates a single ``IRPInstance`` — one scenario (demand realisation +
initial inventory levels) that the solvers operate on.

The instance is loaded from a JSON file produced externally (e.g. a
scenario generator). The JSON is expected to have the structure:

    {
        "Demand":         { "<location>-<product>": [d_0, d_1, ..., d_{T-1}] },
        "Initial levels": { "<location>-<product>": float }
    }

Usage
-----
    from data.loader import load_data
    from instance import create_instance

    data     = load_data("small", "Data")
    instance = create_instance(raw=json_dict, data=data, demand_coefficient=1.0)
"""

from __future__ import annotations

import numpy as np
from dataclasses import dataclass, field, replace as dc_replace
from typing import Dict, List, Literal, Optional, Tuple

from data.models import Node
from data.loader import IRPData


# ---------------------------------------------------------------------------
# Per-route metadata record
# ---------------------------------------------------------------------------

@dataclass
class RouteRecord:
    """
    Metadata stored for every route in the pool, regardless of origin.

    Fields populated for ALL routes
    --------------------------------
    route_id         : integer index in the pool (matches the key in RoutePool.route_records)
    origin           : how the route entered the pool:
                         "dummy"     — the initial no-op route (id=0)
                         "warmstart" — generated by the heuristic route generator
                         "cg"        — discovered by a column-generation pricing subproblem
    stops            : ordered list of node indices  [parking, depot, stn, ..., parking]
    duration         : total driving time in hours (including 0.15h stop time per arc)
    n_stations       : number of station nodes visited
    n_depots         : number of depot nodes visited

    Fields populated only for CG/BP routes  (None for dummy and warmstart)
    -----------------------------------------------------------------------
    tree_level       : depth in the B&P tree at which this route was found.
                       0 = root CG (before any branching), 1 = first branch, etc.
    reduced_cost     : reduced cost at the moment of generation (negative = improving)

    RMP usage statistics  (updated after every LP solve in the CG loop)
    -------------------------------------------------------------------
    times_feasible   : number of RMP solves where this route was in the feasible
                       set for at least one (truck, day) pair
    times_selected   : number of RMP solves where the LP value W[v,t,r] > 1e-6
                       for at least one (truck, day) pair
    cumulative_lp_value : sum of W[v,t,r] across ALL (v,t) pairs and ALL RMP
                          solves — measures total fractional usage
    usage_ratio      : times_selected / times_feasible  (0.0 if never feasible)
    avg_lp_value     : cumulative_lp_value / times_feasible  (0.0 if never feasible)
    """
    # Core identity
    route_id:    int
    origin:      Literal["dummy", "warmstart", "cg"]
    stops:       List[int]
    duration:    float
    n_stations:  int
    n_depots:    int

    # CG/BP specifics (None for dummy and warmstart)
    tree_level:    Optional[int]   = None
    reduced_cost:  Optional[float] = None

    # RMP usage statistics (updated incrementally by RoutePool.update_rmp_stats)
    times_feasible:      int   = 0
    times_selected:      int   = 0
    cumulative_lp_value: float = 0.0

    # Degeneracy flag: True if the route was added to the pool but had zero
    # weight in the very next RMP solve (degenerate pivot / no improvement)
    degenerate:          bool  = False

    # How the subproblem was solved to generate this route
    # "heuristic"  — greedy or stochastic heuristic (Gurobi not called)
    # "suboptimal" — Gurobi terminated early (time limit or early stop)
    # "optimal"    — Gurobi solved to proven optimality
    # None         — not applicable (dummy or warmstart routes)
    generation_quality:  Optional[str]  = None

    @property
    def usage_ratio(self) -> float:
        """Fraction of RMP solves where this route had positive LP weight."""
        return self.times_selected / self.times_feasible if self.times_feasible > 0 else 0.0

    @property
    def avg_lp_value(self) -> float:
        """Average LP value per RMP solve in which the route was feasible."""
        return self.cumulative_lp_value / self.times_feasible if self.times_feasible > 0 else 0.0


# ---------------------------------------------------------------------------
# Column-generation route pool
# ---------------------------------------------------------------------------

@dataclass
class RoutePool:
    """
    Mutable container for all routes discovered during column generation.

    Attributes
    ----------
    R               : current number of routes (including the dummy route 0)
    route_durations : list of route durations in hours; index = route id
                      route 0 is a dummy 'stay at parking' route with a large
                      duration so it is never selected when a real route exists
    route_edges     : dict  route_id -> (N×N) binary numpy array
                      route_edges[r][i,j] = 1 iff edge (i,j) is in route r
    edge_routes     : dict  (i,j) -> list of route ids that contain edge (i,j)
                      used to build the sigma constraints in the RMP
    new_routes      : dict  route_id -> ordered list of node indices
                      e.g. {1: [parking, depot, stn1, stn2, parking]}
    feasible_routes : dict  (v,t) -> list of route ids feasible for truck v on day t
    mandatory_edges : dict  (v,t) -> list of (i,j) edges forced ON  (B&P)
    forbidden_edges : dict  (v,t) -> list of (i,j) edges forced OFF (B&P)
    reduced_costs   : dict  route_id -> reduced cost at the time of generation
    route_records   : dict  route_id -> RouteRecord  (metadata + usage stats)
    """
    R:               int
    route_durations: List[float]
    route_edges:     Dict[int, np.ndarray]
    edge_routes:     Dict[Tuple[int, int], List[int]]
    new_routes:      Dict[int, List[int]]
    feasible_routes: Dict[Tuple[int, int], List[int]]
    mandatory_edges: Dict[Tuple[int, int], List[Tuple[int, int]]]
    forbidden_edges: Dict[Tuple[int, int], List[Tuple[int, int]]]
    reduced_costs:   Dict[int, float]            = field(default_factory=dict)
    route_records:   Dict[int, RouteRecord]      = field(default_factory=dict)

    def update_rmp_stats(self, W_sol: Dict, V: int, T: int) -> None:
        """
        Update RMP usage statistics for every route after one LP solve.

        Should be called once after every call to ``solve_rmp`` in the
        column-generation loop.

        Parameters
        ----------
        W_sol : sparse dict  (v, t, r) -> float  of nonzero LP values,
                as returned by RMPSolution.W_sol
        V     : number of trucks  (from instance.data.V)
        T     : planning horizon  (inferred from demand length)
        """
        # Collect which routes were selected and their total LP weight this solve
        selected:   Dict[int, float] = {}   # route_id -> sum of W[v,t,r] over (v,t)
        for (v, t, r), val in W_sol.items():
            if val > 1e-6:
                selected[r] = selected.get(r, 0.0) + val

        # Determine which routes were in ANY feasible set this solve
        feasible_this_solve = set()
        for vt_list in self.feasible_routes.values():
            feasible_this_solve.update(vt_list)

        # Update each record
        for r, rec in self.route_records.items():
            if r in feasible_this_solve:
                rec.times_feasible += 1
                if r in selected:
                    rec.times_selected      += 1
                    rec.cumulative_lp_value += selected[r]


# ---------------------------------------------------------------------------
# The instance itself
# ---------------------------------------------------------------------------

@dataclass
class IRPInstance:
    """
    A fully specified IRP scenario ready to be passed to any solver.

    Attributes
    ----------
    initial_levels     : dict  Node -> float  (inventory at start of horizon)
    demand             : dict  Node -> list[float]  (demand per period)
    routes             : RoutePool  (initialised with just the dummy route)
    data               : IRPData  (back-reference to the static network data)
    demand_coefficient : scaling factor applied to raw demand values
    """
    initial_levels:     Dict[Node, float]
    demand:             Dict[Node, List[float]]
    routes:             RoutePool
    data:               IRPData
    demand_coefficient: float = 1.0


# ---------------------------------------------------------------------------
# Factory function
# ---------------------------------------------------------------------------

def create_instance(
    raw:                dict,
    data:               IRPData,
    demand_coefficient: float = 1.0,
    V:                  int   = None,
) -> IRPInstance:
    """
    Build an ``IRPInstance`` from a raw JSON dict and pre-loaded network data.

    Parameters
    ----------
    raw                : dict loaded from the scenario JSON file with keys
                         'Demand' and 'Initial levels'
    data               : IRPData returned by ``load_data()``
    demand_coefficient : multiply all demand values by this factor
                         (useful for sensitivity analysis)
    V                  : number of trucks to use in this experiment.
                         Defaults to data.V (all trucks in the network).
                         Pass e.g. V=1 to run a single-truck experiment
                         without reloading the network data.

    Returns
    -------
    IRPInstance
    """
    # ------------------------------------------------------------------
    # Scope V to the experiment size.
    # Only replace init fields (Trucks, tank_cap). V, N, P, C are
    # init=False and recomputed by __post_init__ from len(Trucks).
    # ------------------------------------------------------------------
    if V is None or V == data.V:
        scoped_data = data
    elif V > data.V:
        raise ValueError(
            f"Requested V={V} trucks but the network only has {data.V}."
        )
    else:
        scoped_data = dc_replace(
            data,
            Trucks=data.Trucks[:V],
            tank_cap=data.tank_cap[:V],
        )

    V = scoped_data.V
    N = scoped_data.N

    # ------------------------------------------------------------------
    # Build demand and initial_levels dicts keyed by Node
    # ------------------------------------------------------------------
    initial_levels: Dict[Node, float] = {}
    demand:         Dict[Node, List[float]] = {}

    for node in scoped_data.Nodes:
        if node.location_type != "Station":
            continue

        key = f"{node.location.name}-{node.product.name}"

        if key not in raw["Demand"]:
            raise KeyError(
                f"Key '{key}' not found in JSON 'Demand'. "
                f"Check that location and product names match the network data."
            )
        if key not in raw["Initial levels"]:
            raise KeyError(
                f"Key '{key}' not found in JSON 'Initial levels'."
            )

        demand[node]         = [demand_coefficient * d for d in raw["Demand"][key]]
        initial_levels[node] = raw["Initial levels"][key]

    # ------------------------------------------------------------------
    # Infer T from the demand series length
    # ------------------------------------------------------------------
    T_inferred = len(next(iter(demand.values())))

    # ------------------------------------------------------------------
    # Initialise the route pool with only the dummy 'no-op' route (id=0)
    # ------------------------------------------------------------------
    feasible_routes: Dict[Tuple[int, int], List[int]] = {}
    mandatory_edges: Dict[Tuple[int, int], List]       = {}
    forbidden_edges: Dict[Tuple[int, int], List]       = {}

    for v in range(V):
        for t in range(T_inferred):
            feasible_routes[(v, t)] = [0]
            mandatory_edges[(v, t)] = []
            forbidden_edges[(v, t)] = []

    dummy_record = RouteRecord(
        route_id=0,
        origin="dummy",
        stops=[scoped_data.parking_index, scoped_data.parking_index],
        duration=10_000.0,
        n_stations=0,
        n_depots=0,
    )

    routes = RoutePool(
        R=1,
        route_durations=[10_000.0],
        route_edges={0: np.zeros((N, N))},
        edge_routes={},
        new_routes={},
        feasible_routes=feasible_routes,
        mandatory_edges=mandatory_edges,
        forbidden_edges=forbidden_edges,
        reduced_costs={},
        route_records={0: dummy_record},
    )

    return IRPInstance(
        initial_levels=initial_levels,
        demand=demand,
        routes=routes,
        data=scoped_data,
        demand_coefficient=demand_coefficient,
    )